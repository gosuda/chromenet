#!/bin/sh
# Copies built chrome_net_server binaries into internal/embedded/bin, their license texts into
# third_party/chromium/notices, and rewrites internal/embedded/hashes.go with their digests.
#
# Usage: scripts/engine/pin-embedded.sh DIST RELEASE CHROMIUM_VERSION
#   RELEASE names the build in hashes.go: a release tag (release.yml) or chromium-<version>
#   (chromium.yml).
#   DIST holds chrome_net_server_<goos>_<goarch>[.exe] and NOTICE_<goos>_<goarch>.txt for all six
#   platforms.
set -eu

[ $# -eq 3 ] || { echo "usage: $0 DIST RELEASE CHROMIUM_VERSION" >&2; exit 2; }
dist=$1
release=$2
chromium=$3
root=$(cd "$(dirname "$0")/../.." && pwd)
emb=$root/internal/embedded

sha256_of() {
	if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

entries=
for plat in darwin_amd64 darwin_arm64 linux_amd64 linux_arm64 windows_amd64 windows_arm64; do
	ext=
	case $plat in windows_*) ext=.exe ;; esac
	src=$dist/chrome_net_server_$plat$ext
	[ -f "$src" ] || { echo "pin-embedded: missing $src" >&2; exit 1; }
	[ -f "$dist/NOTICE_$plat.txt" ] || { echo "pin-embedded: missing $dist/NOTICE_$plat.txt" >&2; exit 1; }
	cp "$dist/NOTICE_$plat.txt" "$root/third_party/chromium/notices/$plat.txt"
	cp "$src" "$emb/bin/chrome_net_server_$plat$ext"
	chmod 755 "$emb/bin/chrome_net_server_$plat$ext"
	entries="$entries	\"${plat%_*}/${plat#*_}\": mustHash(\"$(sha256_of "$src")\"),
"
done

cat >"$emb/hashes.go" <<EOF
// Code generated by scripts/engine/pin-embedded.sh. DO NOT EDIT.

package embedded

import "gosuda.org/hqq/secureexec"

const (
	// Version is the release that built the embedded binaries.
	Version = "$release"
	// ChromiumVersion is the Chromium release whose network stack they contain.
	ChromiumVersion = "$chromium"
)

// ReleaseHashes maps "<GOOS>/<GOARCH>" to the SHA-256 digest of the embedded
// chrome_net_server binary.
var ReleaseHashes = map[string]secureexec.Hash{
$entries}

// ExpectedHash returns the pinned SHA-256 digest of chrome_net_server for goos/goarch.
func ExpectedHash(goos, goarch string) (secureexec.Hash, bool) {
	h, ok := ReleaseHashes[goos+"/"+goarch]
	return h, ok
}

func mustHash(s string) secureexec.Hash {
	h, err := secureexec.ParseHash(s)
	if err != nil {
		panic(err)
	}
	return h
}
EOF
gofmt -w "$emb/hashes.go"
